export function getBoardGame(slug: string) {
  return BOARD_GAMES.find((g) => g.slug === slug);
}

// เกมแนวใกล้เคียง: เรียงตามจำนวนแนวเกมที่ตรงกัน แล้วตามลำดับใน playlist ที่ใกล้กัน
export function getRelatedGames(game: BoardGame, limit = 4) {
  const index = BOARD_GAMES.indexOf(game);
  return BOARD_GAMES.map((g, i) => ({
    g,
    shared: g.genres.filter((genre) => game.genres.includes(genre)).length,
    distance: Math.abs(i - index),
  }))
    .filter(({ g, shared }) => g !== game && shared > 0)
    .sort((a, b) => b.shared - a.shared || a.distance - b.distance)
    .slice(0, limit)
    .map(({ g }) => g);
}
